package silverbell.common;

/**
 * 서버와 클라이언트가 주고받는 메시지 종류. PRD 9절 통신 프로토콜과 같다.
 *
 * <p>각 상수의 주석은 「방향 · 담는 값(순서대로) · 관련 기능 ID」다.
 * 값이 여러 개면 {@link Message#values(int)}로 꺼낸다. 사람이 쓴 글은 항상 마지막 값이다.
 * 메시지를 새로 만들면 여기와 PRD 9절을 같이 고친다.
 */
public enum MessageType {

    // ── 접속·대기실 ─────────────────────────────
    /** 클라 → 서버 · 닉네임 · A1 서버 접속 */
    JOIN,
    /** 서버 → 클라 · (없음) · A1 서버 접속 */
    JOIN_OK,
    /** 서버 → 클라 · 실패 사유(닉네임 중복 / 인원 초과 / 게임 진행 중) · A1, A2 */
    JOIN_FAIL,
    /** 서버 → 전체 · 방장;준비 상태가 붙은 참가자 목록 · A2 참가자 목록, A3 게임 시작 */
    USERS,
    /** 클라 → 서버 · 준비 / 준비 취소 · A3 게임 시작 */
    READY,
    /** 방장 → 서버 · (없음) · A3 게임 시작 */
    START,
    /** 서버 → 전체 · 카운트다운 초 · A3 게임 시작 */
    COUNTDOWN,
    /** 클라 → 서버 · (없음) · G1 참가자 퇴장 */
    QUIT,

    // ── 채팅 ───────────────────────────────────
    /** 클라 → 서버 · 메시지 / 서버 → 전체 · 닉네임;메시지 · B1 채팅, B3 정답 가리기 */
    CHAT,
    /** 클라 → 서버 · 받는 사람;메시지 / 서버 → 대상 · 보낸 사람;메시지 · B4 채팅 명령어 */
    WHISPER,
    /** 서버 → 전체 · 안내 문구 · B2 시스템 메시지 */
    SYSTEM,
    /** 방장 → 서버 · (없음) · B4 채팅 명령어 */
    SKIP,

    // ── 문제 ───────────────────────────────────
    /** 서버 → 전체 · 번호;유형;난이도;제한 시간;보기1;보기2;보기3;보기4;문제 · C1 문제 제시, C2 문제 타이머 */
    QUESTION,
    /** 서버 → 전체 · 힌트 단계;초성 힌트;바뀐 점수 · C4 초성 힌트 */
    HINT,
    /** 서버 → 전체 · 정답 · C2 문제 타이머 */
    REVEAL,

    // ── 벨·답안 ─────────────────────────────────
    /** 클라 → 서버 · (없음) · D1 벨 누르기 */
    BUZZ,
    /** 서버 → 전체 · 벨 줄 순서 · D2 벨 대기열, D3 순서 표시 */
    QUEUE,
    /** 서버 → 전체 · 지금 차례인 사람;답변 시간 · D3 순서 표시, D4 답변 시간 */
    TURN,
    /** 클라 → 서버 · 답안 · E1 답안 입력 */
    ANSWER,
    /** 서버 → 전체 · 누가;정답/오답/시간 초과;얻은 점수 · E3 판정 알림, D5 다음 차례 */
    RESULT,

    // ── 점수·종료 ───────────────────────────────
    /** 서버 → 전체 · 사람별 점수 · F1 점수 갱신, F2 점수판 */
    SCORE,
    /** 서버 → 전체 · 최종 순위 · F3 최종 순위 */
    END,

    // ── 힌트 투표 (선택 기능) ────────────────────
    /** 클라 → 서버 → 방장 · 요청한 사람 · H9 힌트 투표 */
    HINT_REQ,
    /** 방장 → 서버 → 전체 · 제한 시간 · H9 힌트 투표 */
    VOTE_OPEN,
    /** 클라 → 서버 · 찬성/반대 · H9 힌트 투표 */
    VOTE,
    /** 서버 → 전체 · 찬성 수;통과 여부 · H9 힌트 투표 */
    VOTE_RESULT
}
