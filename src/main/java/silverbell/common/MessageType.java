package silverbell.common;

/**
 * 서버와 클라이언트가 주고받는 메시지 종류. PRD 9절 통신 프로토콜과 같다.
 *
 * <p>각 상수의 주석은 「방향 · 담는 값(순서대로) · 관련 기능 ID」다.
 * 값이 여러 개면 {@link Message#values(int)}로 꺼낸다. 사람이 쓴 글은 항상 마지막 값이다.
 * 메시지를 새로 만들면 여기와 PRD 9절을 같이 고친다.
 */
public enum MessageType {

    // ── 접속·대기실 ─────────────────────────────
    /** 클라 → 서버 · 닉네임 · A1 서버 접속 */
    JOIN,
    /** 서버 → 클라 · (없음) · A1 서버 접속 */
    JOIN_OK,
    /**
     * 서버 → 클라 · 실패 사유({@link JoinFailReason}: 닉네임 중복 / 인원 초과 / 게임 진행 중 /
     * 닉네임은 1~10자여야 합니다 / 닉네임에 공백이나 ';', '|'를 쓸 수 없습니다) · A1, A2
     */
    JOIN_FAIL,
    /**
     * 서버 → 전체 · 참가자 목록({@code 닉네임:HOST|GUEST:READY|NOT_READY} 형식을 {@code ;}로 구분,
     * 예: {@code User1:HOST:NOT_READY;User2:GUEST:READY}) · A2 참가자 목록, A3 게임 시작
     */
    USERS,
    /** 클라 → 서버 · 준비 / 준비 취소 · A3 게임 시작 */
    READY,
    /** 방장 → 서버 · (없음) · A3 게임 시작 */
    START,
    /** 서버 → 전체 · 카운트다운 초 · A3 게임 시작 */
    COUNTDOWN,
    /** 클라 → 서버 · (없음) · G1 참가자 퇴장 */
    QUIT,

    // ── 채팅 ───────────────────────────────────
    /** 클라 → 서버 · 메시지 / 서버 → 전체 · 닉네임;메시지 · B1 채팅, B3 정답 가리기 */
    CHAT,
    /** 클라 → 서버 · 받는 사람;메시지 / 서버 → 대상 · 보낸 사람;메시지 · B4 채팅 명령어 */
    WHISPER,
    /** 서버 → 전체 · 안내 문구 · B2 시스템 메시지 */
    SYSTEM,
    /** 방장 → 서버 · (없음) · B4 채팅 명령어 */
    SKIP,

    // ── 문제 ───────────────────────────────────
    /** 서버 → 전체 · 번호;유형;난이도;제한 시간;보기1;보기2;보기3;보기4;문제 · C1 문제 제시, C2 문제 타이머 */
    QUESTION,
    /** 서버 → 전체 · 힌트 단계;초성 힌트;바뀐 점수 · C4 초성 힌트 */
    HINT,
    /** 서버 → 전체 · 정답 · C2 문제 타이머 */
    REVEAL,

    // ── 벨·답안 ─────────────────────────────────
    /** 클라 → 서버 · (없음) · D1 벨 누르기 */
    BUZZ,
    /**
     * 서버 → 전체 · 벨 줄 순서 · D2 벨 대기열, D3 순서 표시.
     * 닉네임을 줄 순서대로 {@code ;}로 잇는다. 맨 앞이 지금 차례. 줄이 바뀔 때마다 보낸다(#14).
     * 예: {@code QUEUE|주성;이건;민수}, 줄이 비면 {@code QUEUE|}
     */
    QUEUE,
    /**
     * 서버 → 전체 · 지금 차례인 사람;답변 시간(ms) · D3 순서 표시, D4 답변 시간.
     * 차례가 새로 생기거나 바뀔 때 보낸다(#14·#21). 예: {@code TURN|주성;10000}.
     * 차례 없음(줄이 빔)은 값 없이 {@code TURN|}. 문제 시간 바가 이걸 받고 다시 흐른다(#11).
     * 오답·시간 초과 뒤에는 {@code RESULT}·{@code SCORE}·{@code QUEUE} 다음에 보낸다(#21).
     */
    TURN,
    /**
     * 클라 → 서버 · 답안 · E1 답안 입력.
     * 4지선다는 보기 번호({@code ANSWER|4}), 단답형은 입력칸에 쓴 글({@code ANSWER|피타고라스 정리}).
     * 지금 차례(줄 맨 앞)인 사람이 보낸 것만 채점하고 나머지는 무시한다(#16, N7).
     */
    ANSWER,
    /**
     * 서버 → 전체 · 누가;판정;얻은 점수 · E3 판정 알림, D5 다음 차례.
     * 판정은 {@link AnswerResult}의 {@code 정답}·{@code 오답}(#16)·{@code 시간 초과}(#21). 얻은 점수는 부호 있는 정수.
     * 예: {@code RESULT|이건;정답;2}, {@code RESULT|주성;오답;-1}, {@code RESULT|주성;시간 초과;-1}
     */
    RESULT,

    // ── 점수·종료 ───────────────────────────────
    /** 서버 → 전체 · 사람별 점수 · F1 점수 갱신, F2 점수판 */
    /**
     * 서버 → 전체 · 사람별 점수({@code 닉네임:점수} 형식을 {@code ;}로 구분, 높은 점수 순 정렬,
     * 예: {@code User1:3;User2:-1}) · F1 점수 갱신, F2 점수판
     */
    SCORE,
    /** 서버 → 전체 · 최종 순위 · F3 최종 순위 */
    END,

    // ── 힌트 투표 (선택 기능) ────────────────────
    /** 클라 → 서버 → 방장 · 요청한 사람 · H9 힌트 투표 */
    HINT_REQ,
    /** 방장 → 서버 → 전체 · 제한 시간 · H9 힌트 투표 */
    VOTE_OPEN,
    /** 클라 → 서버 · 찬성/반대 · H9 힌트 투표 */
    VOTE,
    /** 서버 → 전체 · 찬성 수;통과 여부 · H9 힌트 투표 */
    VOTE_RESULT
}
